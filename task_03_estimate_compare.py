# === КОНВЕРТЕР ТЕМПЕРАТУР ===

# Исходные данные
celsius = 25  # температура в градусах Цельсия

# Перевод в Фаренгейты
# Формула: F = C × 9/5 + 32
fahrenheit = celsius * 9/5 + 32

# Определение состояния воды
if celsius <= 0:
    state = "Лёд"
elif celsius >= 100:
    state = "Пар"
else:
    state = "Жидкость"
# Вывод результатов
print("=== КОНВЕРТЕР ТЕМПЕРАТУР ===")
print(f"Температура: {celsius}°C")
print(f"Температура: {fahrenheit}°F")
print(f"Состояние воды: {state}")
